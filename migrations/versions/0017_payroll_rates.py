# ``db/postgres_schema.sql`` is the canonical baseline and already contains
# ``payroll_rates`` and ``reimbursed_in_run_id`` (the repository keeps the DDL
# with the repo so a fresh environment and a migrated one cannot drift). A fresh
# ``alembic upgrade head`` loads that baseline through ``0001_baseline`` and then
# replays every later revision, so this one has to be **idempotent** — the same
# rule `0004`/`0006` follow. Without the guards, upgrading a fresh database fails
# with `DuplicateTable: relation "payroll_rates" already exists`, which is how it
# was found.
UPGRADE = """
CREATE TABLE IF NOT EXISTS payroll_rates (
    version_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_from DATE NOT NULL,
    effective_to   DATE,
    pf_rate        NUMERIC(10,6) NOT NULL CHECK (pf_rate >= 0 AND pf_rate < 1),
    pf_max         NUMERIC(14,2) NOT NULL CHECK (pf_max >= 0),
    esi_rate       NUMERIC(10,6) NOT NULL CHECK (esi_rate >= 0 AND esi_rate < 1),
    esi_max        NUMERIC(14,2) NOT NULL CHECK (esi_max >= 0),
    pt_amount      NUMERIC(14,2) NOT NULL CHECK (pt_amount >= 0),
    pt_threshold   NUMERIC(14,2) NOT NULL CHECK (pt_threshold >= 0),
    tds_slabs      JSONB NOT NULL,
    note           VARCHAR(500),
    created_by     VARCHAR REFERENCES users(emp_id),  -- NULL = system-seeded baseline
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'no_overlapping_rates'
          AND conrelid = 'payroll_rates'::regclass
    ) THEN
        ALTER TABLE payroll_rates
            ADD CONSTRAINT no_overlapping_rates
            EXCLUDE USING gist (
                daterange(effective_from, effective_to, '[)') WITH &&
            );
    END IF;
END
$migration$;
CREATE INDEX IF NOT EXISTS ix_payroll_rates_effective
    ON payroll_rates (effective_from);

ALTER TABLE expense_claims
    ADD COLUMN IF NOT EXISTS reimbursed_in_run_id BIGINT
    REFERENCES payroll_runs(run_id);
CREATE INDEX IF NOT EXISTS ix_expense_claims_reimbursed
    ON expense_claims (reimbursed_in_run_id);

INSERT INTO payroll_rates
    (effective_from, effective_to, pf_rate, pf_max, esi_rate, esi_max,
     pt_amount, pt_threshold, tds_slabs, note, created_by)
SELECT
    DATE '2000-01-01', NULL, 0.12, 1800.00, 0.0075, 21000.00,
    200.00, 10000.00,
    '[{"from_amount": 0, "rate": 0.0},
      {"from_amount": 300000, "rate": 0.05},
      {"from_amount": 600000, "rate": 0.10},
      {"from_amount": 900000, "rate": 0.15},
      {"from_amount": 1200000, "rate": 0.20},
      {"from_amount": 1500000, "rate": 0.30}]'::jsonb,
    'v2.0 baseline: the v1.0 hard-coded rates; Finance must review before go-live (SRS R-01)',
    NULL  -- system-seeded baseline; a human owner is assigned on the first Finance edit
WHERE NOT EXISTS (SELECT 1 FROM payroll_rates);
"""


def upgrade() -> None:
    op.execute(UPGRADE)


def downgrade() -> None:
    op.execute("ALTER TABLE expense_claims DROP COLUMN IF EXISTS reimbursed_in_run_id")
    op.execute("DROP TABLE IF EXISTS payroll_rates")
