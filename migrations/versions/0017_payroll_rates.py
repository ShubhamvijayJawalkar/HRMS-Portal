"""payroll rates: versioned, effective-dated configuration (FR-PAY-03)

Revision ID: 0017_payroll_rates
Revises: 0016_leave_export_jobs

The v1.0 calculation carried every rate as a literal inside ``calc_payroll_item``
(PF 0.12 / ESI 0.0075 / pf_max 1800 / esi_max 21000 / pt 200 / pt_threshold
10000) and a second, private slab ladder inside ``calc_tds``. FR-PAY-03 makes
PF/ESI/PT/TDS **configuration** instead:

* one row per configuration *version* in ``payroll_rates`` —
  effective-dated, non-overlapping (exclusion constraint, the same mechanism as
  ``no_overlapping_structure``), editable only by Finance/Admin at the API, and
  audited on every create;
* a payroll run always resolves the version in force on the run period's end
  date, never "whatever is latest";
* TDS is a validated slab table inside the version (JSONB), applied
  cumulatively by the single calculation function in ``payroll_engine.py``;
* approved-but-unpaid expense claims are linked to the run that reimburses
  them (``expense_claims.reimbursed_in_run_id``) and marked ``Paid`` when it
  finalizes, so a claim can never be paid twice across months.

The seeded row reproduces the v1.0 literals exactly (the old TDS ladder is the
same arithmetic) and is marked as the unreviewed baseline — Finance must review
and version it before go-live (SRS §16 R-01).
"""

from alembic import op

revision = "0017_payroll_rates"
