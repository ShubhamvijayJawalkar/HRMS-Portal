    lop_adjustment  NUMERIC(14,2) NOT NULL DEFAULT 0,
    leave_encashment NUMERIC(14,2) NOT NULL DEFAULT 0,
    deductions      NUMERIC(14,2) NOT NULL DEFAULT 0,
    asset_damage    NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    status          VARCHAR NOT NULL DEFAULT 'Prepared',
    prepared_by     VARCHAR NOT NULL REFERENCES users(emp_id),
    prepared_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    approved_by     VARCHAR REFERENCES users(emp_id),
    approved_at     TIMESTAMPTZ
);
CREATE INDEX ix_offboarding_settlements_offboard ON offboarding_settlements (offboard_id);

-- ══════════════════════════════════════════════════════════════════════════
--  PAYROLL  (FR-PAY)
