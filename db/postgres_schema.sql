CREATE INDEX ix_salary_structures_emp ON salary_structures (emp_id);

CREATE TABLE payroll_runs (
    run_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month               INTEGER NOT NULL,
    year                INTEGER NOT NULL,
    processed_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    status              VARCHAR NOT NULL DEFAULT 'Draft',  -- Draft|Submitted|Approved|Finalized|Cancelled
    submitted_by        VARCHAR REFERENCES users(emp_id),
    submitted_at        TIMESTAMPTZ,
    approved_by         VARCHAR REFERENCES users(emp_id),
