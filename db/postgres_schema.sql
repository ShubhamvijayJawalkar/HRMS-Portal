CREATE INDEX ix_payroll_runs_period ON payroll_runs (year, month);

CREATE TABLE payroll_items (
    item_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            BIGINT NOT NULL REFERENCES payroll_runs(run_id),
    emp_id            VARCHAR NOT NULL REFERENCES users(emp_id),
    gross_salary      NUMERIC(14,2) NOT NULL DEFAULT 0,
    deductions_total  NUMERIC(14,2) NOT NULL DEFAULT 0,
    net_salary        NUMERIC(14,2) NOT NULL DEFAULT 0,
