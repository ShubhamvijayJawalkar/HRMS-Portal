CREATE INDEX ix_offboarding_approvals_offboard ON offboarding_approvals (offboard_id);

-- FR-OFF-03: Finance full-and-final settlement calculation and maker-checker.
CREATE TABLE offboarding_settlements (
    settlement_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offboard_id     BIGINT NOT NULL UNIQUE REFERENCES offboarding_workflow(offboard_id),
