-- ============================================================================
-- HRMS v2.0 — Target PostgreSQL schema (baseline)
-- ============================================================================
-- Source of truth for the Postgres target schema (SRS v2.0 §7, §14 Phase 0-1).
-- This file is split into two parts so it can be used two ways:
--
--   PART A (tables, seed-safe)   — safe to create with dirty legacy data
--   PART B (invariants)          — constraints/indexes activated only after
--                                  the Phase-1 ETL data-cleanup pass runs
--
-- 1. Fresh environment (no data):  run the whole file, or `alembic upgrade head`.
-- 2. Migration environment: the ETL (scripts/migrate_duckdb_to_postgres.py)
--    executes PART A, loads + cleans DuckDB data, then executes PART B.
--
-- Conventions (CC-01..CC-16):
--   * PKs are BIGINT GENERATED BY DEFAULT AS IDENTITY so migrated legacy IDs
--     load directly; a later Phase-3 pass (CC-01) converts to
--     GENERATED ALWAYS and audits gen_id() callers at runtime.
--   * Money is NUMERIC(14,2) (CC-03). Times are TIMESTAMPTZ, UTC (CC-02).
--   * Uniqueness/non-overlap invariants are DB-enforced (CC-05).
-- ============================================================================

BEGIN;

-- Required by the leave-overlap exclusion constraint (CC-05, FR-LEA-02)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ══════════════════════════════════════════════════════════════════════════
--  USERS / IDENTITY / ORG
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE users (
    emp_id                    VARCHAR PRIMARY KEY,
    name                      VARCHAR NOT NULL,
    email                     VARCHAR NOT NULL,
    password                  VARCHAR NOT NULL,
    role                      VARCHAR NOT NULL DEFAULT 'Employee',
    department                VARCHAR,
    designation               VARCHAR,
    manager_emp_id            VARCHAR REFERENCES users(emp_id),
    phone                     VARCHAR,
    date_of_birth             DATE,
    date_of_joining           DATE,
    address                   VARCHAR,          -- PII (pii_reveal)
    emergency_contact_name    VARCHAR,          -- PII
    emergency_contact_phone   VARCHAR,          -- PII
    status                    VARCHAR NOT NULL DEFAULT 'Active',
    allow_login               BOOLEAN NOT NULL DEFAULT TRUE,
    allow_breaks              BOOLEAN NOT NULL DEFAULT TRUE,
    first_login               TIMESTAMPTZ,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_super_admin            BOOLEAN NOT NULL DEFAULT FALSE,   -- §2.2
    candidate_id              BIGINT                              -- FR-ATS-03: reachable only via accepted offer
);
CREATE INDEX ix_users_role_department ON users (role, department);
-- uq_users_email_ci (FR-USR-02, lower(email) unique) lives in PART B: legacy
-- DuckDB never enforced email uniqueness, so duplicates must be resolved in the
-- Phase-1 cleanup pass before this index can be created.

-- Effective-dated shift configuration (FR-ATT-17). Replaces users.shift_start/shift_end.
CREATE TABLE shift_assignments (
    assignment_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id                VARCHAR NOT NULL REFERENCES users(emp_id),
    shift_type            VARCHAR NOT NULL DEFAULT 'Fixed',       -- Fixed | 24x7
    shift_start           TIME NOT NULL,
    shift_end             TIME NOT NULL,
    weekly_off_pattern    VARCHAR DEFAULT 'Sat,Sun',              -- used by FR-LEA-09 / FR-JOB-01
    effective_from        DATE NOT NULL,
    effective_to          DATE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- no_overlapping_shift (invariant) lives in PART B, alongside the other CC-05 rules.
CREATE INDEX ix_shift_assignments_emp ON shift_assignments (emp_id, effective_from);

-- ══════════════════════════════════════════════════════════════════════════
--  AUTH / SESSION
-- ══════════════════════════════════════════════════════════════════════════
-- Session data live in Redis in v2.0 (instant revocation). This table keeps
-- the per-day login/logout record used by attendance/reports (FR-AUTH-05/ATT-08).

CREATE TABLE user_sessions (
    session_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id        VARCHAR NOT NULL REFERENCES users(emp_id),
    login_time    TIMESTAMPTZ NOT NULL,
    logout_time   TIMESTAMPTZ,
    total_hours   NUMERIC(10,2),
    session_date  DATE
);
CREATE INDEX ix_user_sessions_emp_date ON user_sessions (emp_id, session_date);

-- Reset tokens are SHA-256 hashes at rest in v2.0 (FR-AUTH-09). Schema is unchanged.
CREATE TABLE password_reset_tokens (
    token_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id      VARCHAR NOT NULL REFERENCES users(emp_id),
    token       VARCHAR NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used        BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_reset_tokens_emp ON password_reset_tokens (emp_id);

-- TOTP secrets, encrypted at rest (FR-AUTH-11)
CREATE TABLE mfa_credentials (
    cred_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id           VARCHAR NOT NULL REFERENCES users(emp_id),
    secret_encrypted VARCHAR NOT NULL,
    enabled          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at     TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_mfa_emp ON mfa_credentials (emp_id);

-- ══════════════════════════════════════════════════════════════════════════
--  BREAKS
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE break_types (
    break_type           VARCHAR PRIMARY KEY,
    daily_limit_minutes  INTEGER,
    description          VARCHAR
);

CREATE TABLE break_approvals (
    approval_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    break_type   VARCHAR NOT NULL REFERENCES break_types(break_type),
    break_date   DATE NOT NULL,             -- shift date (CC-02)
    reason       VARCHAR,
    status       VARCHAR NOT NULL DEFAULT 'Pending',
    approved_by  VARCHAR REFERENCES users(emp_id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_break_approvals_emp ON break_approvals (emp_id, break_date);

CREATE TABLE breaks (
    break_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id           VARCHAR NOT NULL REFERENCES users(emp_id),
    break_type       VARCHAR NOT NULL REFERENCES break_types(break_type),
    start_time       TIMESTAMPTZ NOT NULL,
    end_time         TIMESTAMPTZ,
    duration_minutes INTEGER,
    break_date       DATE,
    status           VARCHAR NOT NULL DEFAULT 'Active',  -- Active|Completed|Orphaned
    ended_reason     VARCHAR       -- orphan_timeout|admin_dispose|auto_end_new_break (FR-ATT-02/FR-AUTH-14)
);
CREATE INDEX ix_breaks_emp_date ON breaks (emp_id, break_date);

-- ══════════════════════════════════════════════════════════════════════════
--  LEAVE  (FR-LEA)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE leave_requests (
    leave_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    leave_type   VARCHAR NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    year         INTEGER NOT NULL DEFAULT 0,
    "session"    VARCHAR NOT NULL DEFAULT 'Full',   -- Full|First-half|Second-half (FR-LEA-02)
    reason       VARCHAR,
    status       VARCHAR NOT NULL DEFAULT 'Pending',
    approved_by  VARCHAR REFERENCES users(emp_id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ,
    version      INTEGER NOT NULL DEFAULT 1         -- CC-08 optimistic locking
);
CREATE INDEX ix_leave_requests_emp ON leave_requests (emp_id, status);

CREATE TABLE leave_balance (
    balance_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id      VARCHAR NOT NULL REFERENCES users(emp_id),
    leave_type  VARCHAR NOT NULL,
    total_days  INTEGER NOT NULL DEFAULT 0,
    used_days   INTEGER NOT NULL DEFAULT 0,
    reserved    INTEGER NOT NULL DEFAULT 0,         -- FR-LEA-06: reserved by Pending leaves
    year        INTEGER NOT NULL
);
CREATE INDEX ix_leave_balance_emp ON leave_balance (emp_id, year);

-- Per-employee leave policy assignment, effective-dated (FR-LEA-08)
CREATE TABLE leave_policy_assignments (
    assignment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id             VARCHAR NOT NULL REFERENCES users(emp_id),
    location           VARCHAR,
    grade              VARCHAR,
    accrual_rate       NUMERIC(6,2),
    carry_forward_cap  INTEGER,
    encashment_rule    VARCHAR,
    weekly_off_pattern VARCHAR,
    effective_from     DATE NOT NULL,
    effective_to       DATE
);
ALTER TABLE leave_policy_assignments ADD CONSTRAINT no_overlapping_policy
    EXCLUDE USING gist (
        emp_id WITH =,
        daterange(effective_from, effective_to, '[)') WITH &&
    );

CREATE TABLE monthly_leave_grants (
    grant_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id     VARCHAR NOT NULL REFERENCES users(emp_id),
    leave_type VARCHAR NOT NULL,
    days       INTEGER NOT NULL,
    month      INTEGER NOT NULL,
    year       INTEGER NOT NULL,
    granted_by VARCHAR REFERENCES users(emp_id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_leave_grants_emp ON monthly_leave_grants (emp_id, year);

-- Manager → delegate approval authority for a date range (FR-LEA-08a)
CREATE TABLE approval_delegations (
    delegation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delegator_id  VARCHAR NOT NULL REFERENCES users(emp_id),   -- manager
    delegate_id   VARCHAR NOT NULL REFERENCES users(emp_id),
    starts_on     DATE NOT NULL,
    ends_on       DATE NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE approval_delegations ADD CONSTRAINT no_overlapping_delegation
    EXCLUDE USING gist (
        delegator_id WITH =,
        daterange(starts_on, ends_on, '[]') WITH &&
    );

-- ══════════════════════════════════════════════════════════════════════════
--  REGULARIZATION  (FR-REG)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE regularization_requests (
    request_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id                 VARCHAR NOT NULL REFERENCES users(emp_id),
    request_date           DATE NOT NULL,
    reason                 VARCHAR NOT NULL,
    requested_login_time   TIME,       -- FR-REG-02 (was missing in v1.0, A-04)
    requested_logout_time  TIME,
    status                 VARCHAR NOT NULL DEFAULT 'Pending',
    approved_by            VARCHAR REFERENCES users(emp_id),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ,
    version                INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX ix_regularization_emp ON regularization_requests (emp_id, request_date);

-- Output of the nightly attendance job (FR-JOB-01); single source for reports/payroll LOP.
CREATE TABLE attendance_days (
    attendance_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id          VARCHAR NOT NULL REFERENCES users(emp_id),
    attendance_date DATE NOT NULL,
    status          VARCHAR NOT NULL,   -- Present|Half-day|Absent|On Leave|Holiday|Weekly-off
    shift_hours     NUMERIC(8,2),
    source          VARCHAR NOT NULL DEFAULT 'job',
    version         INTEGER NOT NULL DEFAULT 1,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE attendance_days ADD CONSTRAINT uq_attendance_emp_date UNIQUE (emp_id, attendance_date);
CREATE INDEX ix_attendance_days_emp ON attendance_days (emp_id, attendance_date);

-- ══════════════════════════════════════════════════════════════════════════
--  HOLIDAYS  (FR-HOL)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE holidays (
    holiday_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR NOT NULL,
    holiday_date DATE NOT NULL,
    year         INTEGER NOT NULL,
    type         VARCHAR NOT NULL DEFAULT 'National',  -- National|Optional
    location     VARCHAR                               -- per-location applicability (FR-HOL-01)
);
CREATE INDEX ix_holidays_date ON holidays (holiday_date);

CREATE TABLE holiday_optins (
    optin_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id     VARCHAR NOT NULL REFERENCES users(emp_id),
    holiday_id BIGINT NOT NULL REFERENCES holidays(holiday_id),
    status     VARCHAR NOT NULL DEFAULT 'Pending',  -- Pending|Approved|Rejected|Cancelled (FR-HOL-03)
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_holiday_optins_emp ON holiday_optins (emp_id);

-- ══════════════════════════════════════════════════════════════════════════
--  DOCUMENTS / DEPENDENTS  (FR-DOC, FR-USR-11)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE employee_documents (
    doc_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id      VARCHAR NOT NULL REFERENCES users(emp_id),
    doc_type    VARCHAR NOT NULL,
    file_name   VARCHAR,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE documents (
    doc_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id      VARCHAR NOT NULL REFERENCES users(emp_id),
    name        VARCHAR NOT NULL,
    category    VARCHAR NOT NULL DEFAULT 'Other',
    file_path   VARCHAR,      -- random object-storage key in v2.0 (CC-14)
    file_size   INTEGER,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_documents_emp ON documents (emp_id);

CREATE TABLE dependents (
    dependent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    name         VARCHAR NOT NULL,
    relationship VARCHAR NOT NULL,
    date_of_birth DATE
);

-- ══════════════════════════════════════════════════════════════════════════
--  NOTIFICATIONS  (FR-NOT)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id          VARCHAR NOT NULL REFERENCES users(emp_id),
    type            VARCHAR NOT NULL,
    category        VARCHAR DEFAULT 'General',   -- FR-NOT-03 preference category
    message         VARCHAR NOT NULL,
    related_link    VARCHAR,
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,  -- mark-read sets TRUE, never deletes (A-26)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_notifications_emp ON notifications (emp_id, is_read);

-- ══════════════════════════════════════════════════════════════════════════
--  ASSETS  (FR-AST)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE assets (
    asset_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id        VARCHAR NOT NULL REFERENCES users(emp_id),
    asset_type    VARCHAR NOT NULL,
    asset_tag     VARCHAR,
    brand         VARCHAR,
    model         VARCHAR,
    serial_number VARCHAR,
    issued_date   DATE NOT NULL,
    return_date   DATE,
    status        VARCHAR NOT NULL DEFAULT 'Issued',   -- Issued|Returned
    notes         VARCHAR
);
CREATE INDEX ix_assets_emp ON assets (emp_id, status);

-- ══════════════════════════════════════════════════════════════════════════
--  RECRUITMENT / ATS  (FR-ATS)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE job_postings (
    job_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR NOT NULL,
    department   VARCHAR,
    location     VARCHAR,
    description  VARCHAR,
    requirements VARCHAR,
    status       VARCHAR NOT NULL DEFAULT 'Open',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE candidates (
    candidate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       BIGINT REFERENCES job_postings(job_id),
    name         VARCHAR NOT NULL,
    email        VARCHAR NOT NULL,
    phone        VARCHAR,
    resume_text  VARCHAR,
    status       VARCHAR NOT NULL DEFAULT 'Applied',  -- Applied|Screened|Interviewed|Offered|Hired|Rejected|Withdrawn
    applied_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_candidates_job ON candidates (job_id, status);

CREATE TABLE interviews (
    interview_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL REFERENCES candidates(candidate_id),
    scheduled_at TIMESTAMPTZ NOT NULL,
    interviewer  VARCHAR,
    mode         VARCHAR NOT NULL DEFAULT 'In-person',
    feedback     VARCHAR,
    status       VARCHAR NOT NULL DEFAULT 'Scheduled'
);

CREATE TABLE offer_letters (
    offer_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id    BIGINT NOT NULL REFERENCES candidates(candidate_id),
    offered_salary  NUMERIC(14,2),
    basic_pct       NUMERIC(5,2) NOT NULL,   -- FR-ATS-04: three percentages must sum to 100 (A-20)
    hra_pct         NUMERIC(5,2) NOT NULL,
    allowances_pct  NUMERIC(5,2) NOT NULL,
    offer_date      DATE NOT NULL,
    status          VARCHAR NOT NULL DEFAULT 'Pending',
    accepted_at     TIMESTAMPTZ,
    notes           VARCHAR
);

-- ══════════════════════════════════════════════════════════════════════════
--  ONBOARDING  (FR-ONB)
-- ══════════════════════════════════════════════════════════════════════════
-- Legacy *_tasks tables are retained so no v1.0 data is lost; the v2.0
-- workflow tables below are populated by the corrected flows (Phase 4, §6.5).

CREATE TABLE onboarding_tasks (
    task_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    task_name    VARCHAR NOT NULL,
    assigned_to  VARCHAR NOT NULL,
    status       VARCHAR NOT NULL DEFAULT 'Pending',
    due_date     DATE,
    completed_at TIMESTAMPTZ,
    stage        INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE offboarding_tasks (
    task_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    task_name    VARCHAR NOT NULL,
    assigned_to  VARCHAR NOT NULL,
    status       VARCHAR NOT NULL DEFAULT 'Pending',
    due_date     DATE,
    completed_at TIMESTAMPTZ,
    stage        INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE exit_interviews (
    interview_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    reason       VARCHAR NOT NULL,
    feedback     VARCHAR,
    exit_date    DATE NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    offboard_id  BIGINT
);

CREATE TABLE onboarding_workflow (
    workflow_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id       VARCHAR NOT NULL REFERENCES users(emp_id),
    candidate_id BIGINT REFERENCES candidates(candidate_id),
    current_step INTEGER NOT NULL DEFAULT 1,
    step_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    step1_status VARCHAR NOT NULL DEFAULT 'InProgress',
    step2_status VARCHAR NOT NULL DEFAULT 'Pending',
    step3_status VARCHAR NOT NULL DEFAULT 'Pending',
    step4_status VARCHAR NOT NULL DEFAULT 'Pending',
    step5_status VARCHAR NOT NULL DEFAULT 'Pending',
    completed    BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE onboarding_checklist (
    item_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES onboarding_workflow(workflow_id),
    doc_type    VARCHAR NOT NULL,
    status      VARCHAR NOT NULL DEFAULT 'Pending',  -- Pending|Uploaded|Approved|Rejected
    uploaded_at TIMESTAMPTZ,
    reviewed_by VARCHAR REFERENCES users(emp_id),
    review_note VARCHAR,
    reviewed_at TIMESTAMPTZ
);
ALTER TABLE onboarding_checklist ADD CONSTRAINT uq_checklist_item UNIQUE (workflow_id, doc_type);

-- ══════════════════════════════════════════════════════════════════════════
--  OFFBOARDING  (FR-OFF)
-- ══════════════════════════════════════════════════════════════════════════

CREATE TABLE resignations (
    resignation_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id           VARCHAR NOT NULL REFERENCES users(emp_id),
    notice_date      DATE NOT NULL,
    last_working_day DATE NOT NULL,
    reason           VARCHAR,
    initiated_by     VARCHAR NOT NULL,
    status           VARCHAR NOT NULL DEFAULT 'Pending',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    version          INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX ix_resignations_emp ON resignations (emp_id);

CREATE TABLE offboarding_workflow (
    offboard_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resignation_id BIGINT NOT NULL REFERENCES resignations(resignation_id),
    emp_id         VARCHAR NOT NULL REFERENCES users(emp_id),
    stage1_status  VARCHAR NOT NULL DEFAULT 'Pending',
    stage2_status  VARCHAR NOT NULL DEFAULT 'Pending',   -- stages 2 & 3 are independent (parallel, A-16)
    stage3_status  VARCHAR NOT NULL DEFAULT 'Pending',
    stage4_status  VARCHAR NOT NULL DEFAULT 'Pending',
    stage5_status  VARCHAR NOT NULL DEFAULT 'Pending',
    completed      BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_offboarding_workflow_emp ON offboarding_workflow (emp_id, completed);
ALTER TABLE exit_interviews
    ADD CONSTRAINT fk_exit_interviews_offboard
    FOREIGN KEY (offboard_id) REFERENCES offboarding_workflow(offboard_id);

-- FR-OFF-02/03: settlement and stage actions retain a maker-checker trail.
CREATE TABLE offboarding_approvals (
    approval_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offboard_id   BIGINT NOT NULL REFERENCES offboarding_workflow(offboard_id),
    actor_emp_id  VARCHAR NOT NULL REFERENCES users(emp_id),
    action        VARCHAR NOT NULL,       -- Prepare|Approve|Stage1..Stage5
